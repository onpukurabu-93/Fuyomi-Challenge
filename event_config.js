/* ふよみイベントの せってい。まいとし 1月に じどうで きりかわります（せんせいは なにも しなくて OK）。
   ・1月1日〜1月31日が イベント、前の年の 2月1日〜12月31日が れんしゅう。
   ・1月・2月は その年の イベント（2月は きろくを 見る ための 期間）、3月〜12月は つぎの 1月の イベント。
   ・ひづけを かえたい ときは、下の「かたち」を 書きなおして ください。 */
(function () {
  var d = new Date(), y = d.getFullYear(), m = d.getMonth() + 1;
  var Y = (m <= 2) ? y : y + 1;          /* 1〜2月は 今年、3〜12月は らいねん */
  window.FY_EVENT = {
    id: Y + "-01",
    title: "1月の ふよみイベント",
    pStart: (Y - 1) + "-02-01",
    pEnd: (Y - 1) + "-12-31",
    start: Y + "-01-01",
    end: Y + "-01-31"
  };
})();
