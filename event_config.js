/* ふよみイベントの せってい。まいとし 1月に じどうで きりかわります（せんせいは なにも しなくて OK）。
   ・2027年 1月：れんしゅう 12/20〜12/31、イベント 1/1〜1/31（今回だけ）。
   ・2028年 から：れんしゅう 1/1〜1/10、イベント 1/11〜1/31。
   ・1月・2月は その年の イベント（2月は きろくを 見る ための 期間）、3月〜12月は つぎの 1月の イベント。
   ・ひづけを かえたい ときは、下の「かたち」を 書きなおして ください。 */
(function () {
  var d = new Date(), y = d.getFullYear(), m = d.getMonth() + 1;
  var Y = (m <= 2) ? y : y + 1;          /* 1〜2月は 今年、3〜12月は らいねん */
  var ev = (Y <= 2027)
    ? { pStart: (Y - 1) + "-12-20", pEnd: (Y - 1) + "-12-31", start: Y + "-01-01", end: Y + "-01-31" }
    : { pStart: Y + "-01-01", pEnd: Y + "-01-10", start: Y + "-01-11", end: Y + "-01-31" };
  window.FY_EVENT = { id: Y + "-01", title: "1月の ふよみイベント", pStart: ev.pStart, pEnd: ev.pEnd, start: ev.start, end: ev.end };
})();
